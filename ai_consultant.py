    active_stop_price: float           # Current baseline broker stop (e.g. 30% initial stop)
    trigger_candle_open: float = 0.0
    trigger_candle_high: float = 0.0
    trigger_candle_low: float = 0.0
    trigger_candle_close: float = 0.0
