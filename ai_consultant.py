        now_ts = datetime.now().isoformat()
        
        # -------------------------------------------------------------
        # Trap 1: REMOVED (User Directive & Bottleneck Optimization)
        # Midday Dead Zone & VWAP Blender vetoes disabled to unlock high-probability momentum runners.
