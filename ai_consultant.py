    parser = argparse.ArgumentParser(description="AI Consultant CLI Gateway")
    parser.add_argument("--status", action="store_true", help="View currently pending candidate consultation")
    actions = parser.add_mutually_exclusive_group()
    actions.add_argument("--approve", action="store_true", help="Approve currently pending candidate trade")
    actions.add_argument("--veto", action="store_true", help="Veto currently pending candidate trade")
    parser.add_argument("--reason", type=str, default="", help="Rationale for approval or veto")
    parser.add_argument("--trailing", type=str, default="runner_ema9", choices=["runner_ema9", "tight_ema20", "standard"])
    actions.add_argument("--set-sl", type=float, default=None, help="Set AI Stop-Loss price for filled position")
    parser.add_argument("--invalidation", type=float, default=None, help="Set underlying Spot invalidation level")
    parser.add_argument("--request-id", help="Entry or stop consultation request ID from the current dossier")
    args = parser.parse_args()

    if args.status:
        if PENDING_FILE_JSON.exists():
            with open(PENDING_FILE_JSON, "r", encoding="utf-8") as f:
                data = json.load(f)
            print("\n=== CURRENTLY PENDING AI CONSULTATION ===")
            print(f"Created: {data.get('created_at')} | Timeout: {data.get('timeout_seconds')}s")
            if PENDING_FILE_MD.exists():
                with open(PENDING_FILE_MD, "r", encoding="utf-8") as f:
                    print("\n" + f.read())
        else:
            print("\nNo candidate trade is currently awaiting AI consultation.")
        sys.exit(0)

    if args.set_sl is not None:
        try:
            payload = submit_stop_loss_verdict(
                args.request_id, args.set_sl, args.invalidation, args.trailing, args.reason
            )
        except (OSError, ValueError, TypeError, KeyError) as exc:
            parser.error(str(exc))
        print(f"\n[AI STOP-LOSS] Submitted Stop: ₹{args.set_sl:.2f}")
        if args.invalidation:
            print(f"Spot Invalidation: {args.invalidation:.1f}")
        print(f"Reason: {payload['reasoning']}\n")
        sys.exit(0)

    if args.approve or args.veto:
        action = "APPROVED" if args.approve else "VETOED"
        reason = args.reason or ("Manual approval via CLI" if args.approve else "Manual veto via CLI")
        try:
            submit_entry_verdict(args.request_id, action, reason, args.trailing)
        except (OSError, ValueError, TypeError, KeyError, AttributeError) as exc:
            parser.error(str(exc))
        print(f"\n[AI CONSULTATION] Submitted Verdict: {action}")
        print(f"Reason: {reason}")
        print(f"Trailing Profile: {args.trailing}\n")
        sys.exit(0)

    parser.print_help()
